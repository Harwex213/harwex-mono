// Ships one API (a package with an `hwApi` field, see src/scan.js) to the droplet:
//
//   DEPLOY_HOST=user@host node src/deploy-api.js <name>
//   node src/deploy-api.js <name> --local     build for this machine, write compose to out/apis/<name>/
//
// It builds the image from api/Dockerfile, streams it over ssh with `docker
// load`, writes a generated compose.yaml into /opt/hw-apis/<name>, and waits
// until the container reports healthy. No registry is involved, as in deploy.sh.
//
// The container is api-<name> on the shared `hw` network. nginx in hw-sites
// serves it at /<name>/api/ by that name, so a new API needs no nginx change.
//
// To build on the droplet instead of the Mac, set DOCKER_HOST=ssh://$DEPLOY_HOST.
//
// Optional on the droplet: /opt/hw-apis/<name>/.env, for secrets. Compose
// passes it to the container when it exists.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { MONOREPO_ROOT, scanApis } from "./scan.js";

const DEPLOY_DIR = resolve(import.meta.dirname, "..");
const DOCKERFILE = join(DEPLOY_DIR, "api/Dockerfile");
const PORT = 8080;

function run(command, args, options = {}) {
  execFileSync(command, args, { stdio: "inherit", ...options });
}

function capture(command, args, options = {}) {
  return execFileSync(command, args, { encoding: "utf8", ...options }).trim();
}

function composeFile(apiName) {
  const service = `api-${apiName}`;
  return `# Generated by packages/infrastructure/deploy/src/deploy-api.js. Edits here are
# lost on the next deploy.
#
# To roll back, pick an older tag from \`docker images ${service}\`:
#   API_TAG=1a6a96e docker compose up -d
name: ${service}

services:
  # The container name is its DNS name on the \`hw\` network. nginx proxies
  # /${apiName}/api/ to http://${service}:${PORT}.
  ${service}:
    image: ${service}:\${API_TAG:-latest}
    container_name: ${service}
    pull_policy: never
    restart: unless-stopped
    env_file:
      - path: .env
        required: false
    volumes:
      - data:/data
    # No published ports. Only nginx reaches the API, over the \`hw\` network.
    networks:
      - hw
    # The slim image has no curl, so node itself makes the request.
    healthcheck:
      test:
        - CMD
        - node
        - -e
        - "fetch('http://localhost:${PORT}/api/health').then((r) => process.exit(r.ok ? 0 : 1), () => process.exit(1))"
      interval: 30s
      timeout: 5s
      retries: 3
      start_period: 20s
      start_interval: 2s

volumes:
  data:

networks:
  # Created once, outside any compose project. This script creates it when
  # missing. Compose will not create an external network.
  hw:
    external: true
`;
}

function imageTag(api) {
  const sha = capture("git", ["rev-parse", "--short", "HEAD"]);
  // Only the package directory: every source that goes into the image lives there.
  const dirty = capture("git", ["status", "--porcelain", "--", api.dir]) !== "";
  return dirty ? `${sha}-dirty` : sha;
}

function buildImage(api, image, tag, platformArgs) {
  if (api.hasBuild) {
    console.log(`==> building ${api.name}`);
    run("yarn", ["workspace", api.name, "run", "build"], { cwd: MONOREPO_ROOT });
  }
  // --provenance=false keeps the result a plain single-platform image. With
  // provenance on, buildx wraps it in a manifest list, which the droplet's
  // classic image store can refuse to load.
  console.log(`==> building image ${image}:${tag}`);
  run("docker", [
    "build", ...platformArgs, "--provenance=false",
    "-f", DOCKERFILE,
    "-t", `${image}:${tag}`, "-t", `${image}:latest`,
    api.dir,
  ]);
}

function deployLocal(api, image, tag) {
  buildImage(api, image, tag, []);
  const dir = join(DEPLOY_DIR, "out/apis", api.apiName);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "compose.yaml"), composeFile(api.apiName));
  console.log(`==> built ${image}:${tag}; start it with: docker compose -f ${join(dir, "compose.yaml")} up -d`);
}

function deployRemote(api, image, tag, host) {
  const remoteDir = `/opt/hw-apis/${api.apiName}`;

  console.log(`==> checking ${host}`);
  run("ssh", [host, `docker version > /dev/null \
    && { docker network inspect hw > /dev/null 2>&1 || docker network create hw > /dev/null; } \
    && mkdir -p ${remoteDir}`]);

  // The Mac is arm64 and the droplet is amd64. Without --platform the container
  // exits with "exec format error", and npm inside the build would fetch arm64
  // native binaries.
  buildImage(api, image, tag, ["--platform", "linux/amd64"]);

  // With DOCKER_HOST=ssh://<the droplet> the build already ran in the droplet's
  // own Docker, which helps when Docker on the Mac is down. The image is then in
  // place, and streaming it would only send it to the Mac and back.
  if (process.env.DOCKER_HOST === `ssh://${host}`) {
    console.log(`==> image was built on ${host}, nothing to stream`);
  } else {
    // Both tags name the same image, so the layers are sent once. The extra tag
    // is what makes a rollback possible on the droplet.
    console.log(`==> streaming image to ${host}`);
    run("bash", ["-c", "set -o pipefail; docker save \"$1\" \"$2\" | ssh \"$3\" docker load", "_", `${image}:${tag}`, `${image}:latest`, host]);
  }

  console.log("==> restarting");
  const staging = mkdtempSync(join(tmpdir(), "hw-api-"));
  try {
    writeFileSync(join(staging, "compose.yaml"), composeFile(api.apiName));
    run("scp", ["-q", join(staging, "compose.yaml"), `${host}:${remoteDir}/compose.yaml`]);
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }

  // --force-recreate because :latest keeps its name across deploys. The loop
  // waits for the healthcheck: "running" alone is not enough, because a server
  // that crashes after a second still counts as running at first.
  run("ssh", [host, `cd ${remoteDir} \
    && docker compose up -d --force-recreate \
    && for i in $(seq 30); do \
         status=$(docker inspect --format '{{.State.Health.Status}}' ${image}); \
         [ "$status" = healthy ] && break; \
         sleep 1; \
       done \
    && if [ "$status" != healthy ]; then \
         echo "container is not healthy ($status):" >&2; \
         docker compose logs --tail 30 >&2; \
         exit 1; \
       fi \
    && docker image prune -f > /dev/null`]);

  console.log(`==> deployed ${image}:${tag} at /${api.apiName}/api/`);
}

function main() {
  const [apiName, flag] = process.argv.slice(2);
  const apis = scanApis();
  const api = apis.find((candidate) => candidate.apiName === apiName);
  if (!api) {
    const known = apis.map((candidate) => candidate.apiName).join(", ") || "none";
    throw new Error(`usage: deploy-api <name> [--local]; known APIs: ${known}`);
  }

  const image = `api-${api.apiName}`;
  const tag = imageTag(api);
  if (flag === "--local") {
    deployLocal(api, image, tag);
    return;
  }

  const host = process.env.DEPLOY_HOST;
  if (!host) {
    throw new Error("set DEPLOY_HOST, e.g. deploy@harwex.example");
  }
  deployRemote(api, image, tag, host);
}

main();
